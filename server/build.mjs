export function build(file = path.join(here, 'dist/games.js'), only = null) {
  let out = '// Generated by server/build.mjs from the game cores. Do not edit.\n';
  const list = GAMES.filter(g => (!only || only.includes(g.id)) && (/\brecord:\[/.test(fs.readFileSync(path.join(repo, g.file), 'utf8'))));
  for (const g of list) {
    const src = fs.readFileSync(path.join(repo, g.file), 'utf8');
    // The core is a classic script: (function(g){...})(globalThis). Run it against a private object.
    out += `\nconst ${g.global} = (() => { const globalThis = {}; const module = undefined;\n${src}\nreturn globalThis.${g.global}; })();\n`;
  }
  out += '\nexport const GAMES = {\n' + list.map(g => `  ${JSON.stringify(g.id)}: { core: ${g.global}, create: seed => new ${g.global}.${g.engine}(seed), version: ${g.global}.CONFIG.version, step: ${g.global}.CONFIG.step, record: ${g.global}.CONFIG.record },`).join('\n') + '\n};\n';
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  return file;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log('wrote ' + path.relative(repo, build()));
